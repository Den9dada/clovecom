import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main(List<String> args) async {
  if (!Platform.isWindows) {
    throw UnsupportedError('Winsock 绑定须在安装 Windows SDK 的 Windows 上生成');
  }
  final root = Platform.script.resolve('../');
  if (args.contains('--serial-loop')) {
    final clang = Platform.environment['LIBCLANG_PATH'];
    await _generateSerialLoop(root, clang == null ? null : Uri.file(clang));
    return;
  }
  final sdkRoot =
      Platform.environment['WINDOWS_SDK_INCLUDE'] ??
      r'C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0';
  final vcRoot = Platform.environment['MSVC_INCLUDE'];
  final libclang = Platform.environment['LIBCLANG_PATH'];
  await FfiGenerator(
    input: Input(
      entryPoints: [
        root.resolve('third_party/windows_winsock/windows_winsock.h'),
      ],
      compilerOptions: [
        '--target=x86_64-pc-windows-msvc',
        '-fms-extensions',
        '-I$sdkRoot/um',
        '-I$sdkRoot/shared',
        '-I$sdkRoot/ucrt',
        if (vcRoot != null) '-I$vcRoot',
      ],
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {
            'WSAStartup',
            'WSACleanup',
            'WSAGetLastError',
            'WSACreateEvent',
            'WSACloseEvent',
            'WSAEventSelect',
            'WSAEnumNetworkEvents',
            'setsockopt',
          }.contains(node.originalName);
          node.recordUse = node.isIncluded;
        },
        struct: (node) {
          node.isIncluded =
              node.originalName == 'WSAData' ||
              node.originalName == '_WSANETWORKEVENTS';
          if (node.originalName == '_WSANETWORKEVENTS') {
            node.name = 'WSANETWORKEVENTS';
          }
        },
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/third_party/windows_winsock.g.dart'),
      ),
      recordUseMapping: root.resolve(
        'lib/src/third_party/windows_winsock.record_use_mapping.g.dart',
      ),
      style: const NativeExternalBindings(
        assetId: 'package:clovecom/src/third_party/windows_winsock.g.dart',
      ),
      preamble: '''
// Generated by package:ffigen. Do not edit manually.
// Regenerate: dart run tool/ffigen.dart
// Source: Microsoft Windows SDK winsock2.h (Microsoft SDK license).
// Native header copyright notice:
// Winsock2.h -- definitions to be used with the WinSock 2 DLL and
//                WinSock 2 applications.
// This header file corresponds to version 2.2.x of the WinSock API
// specification.
// This file includes parts which are Copyright (c) 1982-1986 Regents
// of the University of California. All rights reserved. The
// Berkeley Software License Agreement specifies the terms and
// conditions for redistribution.
// Generated declarations only; no Windows SDK headers are redistributed.
// ignore_for_file: type=lint, unused_import, unused_element, experimental_member_use
''',
    ),
  ).generate(libclangDylib: libclang == null ? null : Uri.file(libclang));
}

Future<void> _generateSerialLoop(Uri root, Uri? libclang) {
  return FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('windows/runner/native_serial_loop.h')],
      compilerOptions: ['--target=x86_64-pc-windows-msvc'],
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {
            'CloveSerialLoopStartTimed',
            'CloveSerialLoopUpdate',
            'CloveSerialLoopDrainShared',
            'CloveSerialLoopRoundsReady',
            'CloveSerialLoopStop',
            'CloveSerialLoopRelease',
          }.contains(node.originalName);
        },
        macroConstant: (node) {
          node.isIncluded = node.originalName == 'CLOVESERIAL_LOOP_MAX_PAYLOAD';
          if (node.isIncluded) node.name = 'nativeSerialLoopMaxPayloadBytes';
        },
        struct: (node) => node.isIncluded = {
          'CloveSerialRound',
          'CloveSerialLoopStatus',
        }.contains(node.originalName),
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/services/serial/native_serial_loop.g.dart'),
      ),
      style: const DynamicLibraryBindings(wrapperName: 'NativeSerialLoopApi'),
      preamble: '''
// Generated by package:ffigen. Do not edit manually.
// Regenerate: dart run tool/ffigen.dart --serial-loop
// ignore_for_file: type=lint, experimental_member_use
''',
    ),
  ).generate(libclangDylib: libclang);
}
